#!/usr/bin/env python3

from __future__ import annotations

import argparse
import csv
from decimal import Decimal, ROUND_HALF_EVEN
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
EVOLUTION = ROOT / "data" / "evolution.tsv"
PRO_PRIMARY = ROOT / "data" / "pro-primary.tsv"
INTEL_CONTROL = ROOT / "data" / "intel-control.tsv"
HOST_REPRODUCTION = ROOT / "data" / "host-reproduction.tsv"
TARGET = ROOT / "Path22" / "Data.lean"
TIMES = (0, 50, 100, 200, 350, 500)
CASES = ("path22_music", "phase_erased_control")


def scaled(value: str, factor: int, *, signed: bool = False) -> int:
    result = int((Decimal(value) * factor).to_integral_value(rounding=ROUND_HALF_EVEN))
    if not signed and result < 0:
        raise ValueError("negative value for Nat certificate")
    return result


def load_rows() -> dict[tuple[str, int], dict[str, str]]:
    rows: dict[tuple[str, int], dict[str, str]] = {}
    with EVOLUTION.open(encoding="utf-8", newline="") as stream:
        for row in csv.DictReader(stream, delimiter="\t"):
            key = (row["case"], int((Decimal(row["time"]) * 1000).to_integral_value()))
            if key in rows:
                raise ValueError(f"duplicate row: {key}")
            rows[key] = row
    expected = {(case, time) for case in CASES for time in TIMES}
    if set(rows) != expected:
        raise ValueError(f"certificate rows differ: {set(rows) ^ expected}")
    return rows


def read_table(path: Path) -> list[dict[str, str]]:
    with path.open(encoding="utf-8", newline="") as stream:
        return list(csv.DictReader(stream, delimiter="\t"))


def reference_case(
    rows: dict[tuple[str, int], dict[str, str]], case: str
) -> list[dict[str, str]]:
    return [rows[(case, time)] for time in TIMES]


def compare_independent(
    reference: list[dict[str, str]],
    independent: list[dict[str, str]],
    *,
    tolerance: Decimal,
    relative: bool,
) -> bool:
    if len(reference) != len(independent):
        return False
    for expected, observed in zip(reference, independent):
        if expected.keys() != observed.keys() or expected["case"] != observed["case"]:
            return False
        for key in expected:
            if key == "case" or key == "trace_pass":
                if expected[key] != observed[key]:
                    return False
                continue
            left = Decimal(expected[key])
            right = Decimal(observed[key])
            scale = max(Decimal(1), abs(left), abs(right)) if relative else Decimal(1)
            if abs(left - right) > tolerance * scale:
                return False
    return True


def verify_reproductions(rows: dict[tuple[str, int], dict[str, str]]) -> tuple[bool, bool]:
    pro = compare_independent(
        reference_case(rows, "path22_music"),
        read_table(PRO_PRIMARY),
        tolerance=Decimal(0),
        relative=False,
    )
    intel = compare_independent(
        reference_case(rows, "phase_erased_control"),
        read_table(INTEL_CONTROL),
        tolerance=Decimal("1e-9"),
        relative=False,
    )
    hosts = read_table(HOST_REPRODUCTION)
    if len(hosts) != 3 or {row["host"] for row in hosts} != {
        "Taylors-Mac-Studio",
        "DobeWorks-01",
        "agar-MacBook-Pro",
    }:
        raise ValueError("host reproduction manifest differs")
    if not pro or not intel:
        raise ValueError("independent host reproduction differs")
    return pro, intel


def definitions(
    rows: dict[tuple[str, int], dict[str, str]], pro: bool, intel: bool
) -> list[str]:
    lines = [
        "/- Generated by scripts/render_certificate.py. Do not edit by hand. -/",
        "namespace Path22",
        "",
        "def bodyForce : Int × Int × Int := (0, 0, 0)",
        f"def proStudioExact : Bool := {str(pro).lower()}",
        f"def intelStudioWithinTolerance : Bool := {str(intel).lower()}",
        "",
    ]
    prefixes = {"path22_music": "music", "phase_erased_control": "control"}
    for case in CASES:
        prefix = prefixes[case]
        for time in TIMES:
            row = rows[(case, time)]
            lines.append(f"def {prefix}Energy{time} : Nat := {scaled(row['energy_fraction'], 10**15)}")
        lines.append("")
        for time in TIMES:
            row = rows[(case, time)]
            lines.append(f"def {prefix}MaxSpeed{time} : Nat := {scaled(row['max_speed'], 10**6)}")
        lines.append("")
        for time in TIMES:
            row = rows[(case, time)]
            lines.append(f"def {prefix}Div{time} : Nat := {scaled(row['normalized_divergence'], 10**18)}")
        lines.append("")
    for time in TIMES:
        row = rows[("path22_music", time)]
        lines.append(f"def musicCosine{time} : Int := {scaled(row['shape_cosine'], 10**9, signed=True)}")
    lines.append("")
    for time in (100, 350, 500):
        row = rows[("path22_music", time)]
        lines.append(f"def musicRetention{time} : Nat := {scaled(row['retention'], 10**12)}")
    lines.extend(["", "end Path22", ""])
    return lines


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    rows = load_rows()
    pro, intel = verify_reproductions(rows)
    rendered = "\n".join(definitions(rows, pro, intel))
    if args.check:
        current = TARGET.read_text(encoding="utf-8")
        if current != rendered:
            raise SystemExit("Path22/Data.lean is not the exact rendering of data/evolution.tsv")
        print("CERTIFICATE_DATA_OK")
    else:
        TARGET.write_text(rendered, encoding="utf-8")
        print(TARGET)


if __name__ == "__main__":
    main()

